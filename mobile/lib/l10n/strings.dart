extension L10nContext on BuildContext {
  String tr(String key, [Map<String, String>? args]) =>
      L10n.translate(Localizations.localeOf(this).languageCode, key, args);

  /// Translates a provider statistic label when we know it, otherwise shows it unchanged.
  String statLabel(String raw) {
    final key = L10n.statKey(raw);
    return key == null ? raw : tr(key);
  }

  bool get isArabic => Localizations.localeOf(this).languageCode == 'ar';
}
